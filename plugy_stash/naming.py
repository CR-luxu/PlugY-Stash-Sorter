"""Automatic page names for sorted PlugY stash pages.

Only blank pages and pages whose name was generated by this module are
renamed.  User-defined page names are preserved.
"""
from __future__ import annotations

import re
from collections import Counter

from .stash import StashFile
from .zh import CATEGORY_ORDER, QUALITY_ORDER, category, quality_category

AUTO_LABELS = set(CATEGORY_ORDER) | set(QUALITY_ORDER) | {"混合"}
_SUFFIX_RE = re.compile(r"\s+\d+$")


def is_auto_name(name: str) -> bool:
    name = name.strip()
    if not name:
        return True
    base = _SUFFIX_RE.sub("", name)
    return all(part in AUTO_LABELS for part in base.split("/"))


def _page_label(page, mode: str) -> str:
    if not page.items:
        return ""
    if mode == "quality":
        values = [quality_category(item) for item in page.items]
    else:
        values = [category(item) for item in page.items]
    counts = Counter(values)
    ordered = counts.most_common()
    if len(ordered) == 1:
        return ordered[0][0]
    total = len(values)
    if ordered[0][1] / total >= 0.72:
        return ordered[0][0]
    top = [name for name, _ in ordered[:2]]
    top.sort(key=lambda name: (CATEGORY_ORDER + QUALITY_ORDER).index(name) if name in (CATEGORY_ORDER + QUALITY_ORDER) else 999)
    return "/".join(top)


def _encode_name(name: str, limit: int = 20) -> bytes:
    raw = name.encode("gbk", errors="replace")
    while len(raw) > limit and name:
        name = name[:-1]
        raw = name.encode("gbk", errors="replace")
    return raw


def name_pages(stash: StashFile, mode: str) -> list[str]:
    """Assign category/quality names to auto-nameable used pages.

    Returns the list of labels that were considered, mainly for tests/logging.
    """
    labels = [_page_label(page, mode) for page in stash.pages]
    counts = Counter(label for label in labels if label)
    seen: Counter[str] = Counter()
    applied: list[str] = []

    for page, label in zip(stash.pages, labels):
        existing = page.name.strip()
        if not page.items:
            # Remove a stale auto-name from a page that became empty.
            if existing and is_auto_name(existing):
                page.name_bytes = b""
            continue
        if existing and not is_auto_name(existing):
            continue
        if not label:
            continue
        seen[label] += 1
        text = label
        if counts[label] > 1:
            text += f" {seen[label]}"
        if text == existing:
            continue
        page.name_bytes = _encode_name(text)
        applied.append(text)
    return applied
